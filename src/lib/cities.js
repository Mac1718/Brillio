/** Resolve a vendor location to map coordinates, falling back to its state. */
export function resolveCity(city, state) {
  const key = String(city || '').trim().toLowerCase()
  if (CITY_COORDS[key]) return { ...CITY_COORDS[key], matched: 'city' }
  const stateKey = String(state || '').trim().toLowerCase()
  if (STATE_CENTROIDS[stateKey]) return { ...STATE_CENTROIDS[stateKey], matched: 'state' }
  return null
}
